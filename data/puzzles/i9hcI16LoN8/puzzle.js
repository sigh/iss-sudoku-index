// Author: Unknown
// Video: https://www.youtube.com/watch?v=i9hcI16LoN8
// Source: https://cracking-the-cryptic.web.app/sudoku/4nFtJMN9Df

// Rules encoded: standard sudoku, plus a shading layer where each box holds
// exactly four shaded cells forming a T, L, or S tetromino (rotations and
// reflections allowed -- "L" also covers the mirrored J, "S" also covers the
// mirrored Z: these are the three asymmetric free tetrominoes, distinct from
// the square and the straight line), each row and column of three boxes uses
// one T, one L, and one S, the shaded cells all connect into a single
// orthogonal region with no 2x2 shaded block, and each box's four shaded
// digits sum to 20 with no two boxes repeating the same four-digit
// combination.
//
// Omitted: the shaded wall must additionally contain no loop (its induced
// adjacency graph must be a tree, not merely connected). ConnectedValues below
// only proves connectivity.

const SHADED = 1;
const UNSHADED = 2;

function* rangeI(from, to) {
  for (let i = from; i <= to; i++) yield i;
}

// Every T/L/S tetromino placement that fits inside a 3x3 box, as box-local
// (row, col) offsets in 0..2. Generated by taking the canonical T, L, and S
// tetrominoes through all 4 rotations and (for L and S) their mirror image,
// then every translation that keeps the 4 cells inside the box. 8 T
// placements + 16 L placements (covering L and J) + 8 S placements (covering
// S and Z) = 32; no cell-set is reachable by two different types.
const PLACEMENTS = [
  { type: 'T', cells: [[0, 0], [0, 1], [0, 2], [1, 1]] },
  { type: 'T', cells: [[0, 0], [1, 0], [1, 1], [2, 0]] },
  { type: 'T', cells: [[0, 1], [1, 0], [1, 1], [1, 2]] },
  { type: 'T', cells: [[0, 1], [1, 0], [1, 1], [2, 1]] },
  { type: 'T', cells: [[0, 1], [1, 1], [1, 2], [2, 1]] },
  { type: 'T', cells: [[0, 2], [1, 1], [1, 2], [2, 2]] },
  { type: 'T', cells: [[1, 0], [1, 1], [1, 2], [2, 1]] },
  { type: 'T', cells: [[1, 1], [2, 0], [2, 1], [2, 2]] },
  { type: 'L', cells: [[0, 0], [0, 1], [0, 2], [1, 0]] },
  { type: 'L', cells: [[0, 0], [0, 1], [0, 2], [1, 2]] },
  { type: 'L', cells: [[0, 0], [0, 1], [1, 0], [2, 0]] },
  { type: 'L', cells: [[0, 0], [0, 1], [1, 1], [2, 1]] },
  { type: 'L', cells: [[0, 0], [1, 0], [1, 1], [1, 2]] },
  { type: 'L', cells: [[0, 0], [1, 0], [2, 0], [2, 1]] },
  { type: 'L', cells: [[0, 1], [0, 2], [1, 1], [2, 1]] },
  { type: 'L', cells: [[0, 1], [0, 2], [1, 2], [2, 2]] },
  { type: 'L', cells: [[0, 1], [1, 1], [2, 0], [2, 1]] },
  { type: 'L', cells: [[0, 1], [1, 1], [2, 1], [2, 2]] },
  { type: 'L', cells: [[0, 2], [1, 0], [1, 1], [1, 2]] },
  { type: 'L', cells: [[0, 2], [1, 2], [2, 1], [2, 2]] },
  { type: 'L', cells: [[1, 0], [1, 1], [1, 2], [2, 0]] },
  { type: 'L', cells: [[1, 0], [1, 1], [1, 2], [2, 2]] },
  { type: 'L', cells: [[1, 0], [2, 0], [2, 1], [2, 2]] },
  { type: 'L', cells: [[1, 2], [2, 0], [2, 1], [2, 2]] },
  { type: 'S', cells: [[0, 0], [0, 1], [1, 1], [1, 2]] },
  { type: 'S', cells: [[0, 0], [1, 0], [1, 1], [2, 1]] },
  { type: 'S', cells: [[0, 1], [0, 2], [1, 0], [1, 1]] },
  { type: 'S', cells: [[0, 1], [1, 0], [1, 1], [2, 0]] },
  { type: 'S', cells: [[0, 1], [1, 1], [1, 2], [2, 2]] },
  { type: 'S', cells: [[0, 2], [1, 1], [1, 2], [2, 1]] },
  { type: 'S', cells: [[1, 0], [1, 1], [2, 1], [2, 2]] },
  { type: 'S', cells: [[1, 1], [1, 2], [2, 0], [2, 1]] },
];
const TYPE_VAL = { T: 1, L: 2, S: 3 };

// The 12 four-digit subsets of 1-9 that sum to 20 -- the full, exhaustive set
// (every box's shaded digits are forced to be one of these, since a box
// already holds all nine digits once each). Nine boxes draw nine of these
// twelve combinations, all different.
const COMBOS = [
  [1, 2, 8, 9], [1, 3, 7, 9], [1, 4, 6, 9], [1, 4, 7, 8], [1, 5, 6, 8],
  [2, 3, 6, 9], [2, 3, 7, 8], [2, 4, 5, 9], [2, 4, 6, 8], [2, 5, 6, 7],
  [3, 4, 5, 8], [3, 4, 6, 7],
];

const givens = [
  ['R1C4', 1], ['R1C7', 9], ['R2C4', 2], ['R2C8', 6], ['R4C1', 4],
  ['R4C7', 1], ['R5C1', 6], ['R5C3', 5], ['R5C5', 8], ['R5C9', 2],
  ['R6C1', 2], ['R6C7', 8], ['R6C8', 4], ['R7C6', 3], ['R7C8', 9],
  ['R8C7', 2], ['R9C3', 2], ['R9C7', 3],
];

// The 16 cells shown pre-shaded on the starting grid.
const preShaded = [
  'R1C1', 'R1C6', 'R1C8', 'R3C5', 'R3C8', 'R4C1', 'R4C4', 'R4C5', 'R4C6',
  'R5C2', 'R7C2', 'R7C8', 'R8C5', 'R8C8', 'R9C3', 'R9C6',
];

// Widened to admit 0 (the masked-overlay "unshaded" sentinel) through 12 (the
// combo-label overlay's index range). Real grid cells are restricted back to
// 1-9 below.
const shape = new Shape('9x9', '0-12');
const graph = cellGraph(shape);

const shade = graph.makeOverlay('VS');
const masked = graph.makeOverlay('VM');
const boxAnchors = [...rangeI(1, 9)].map(b => graph.box(b)[0]);
const typeVar = graph.makeOverlay('VT', boxAnchors);
const comboVar = graph.makeOverlay('VB', boxAnchors);

// digit-masked: the masked cell is either 0 or exactly the grid digit.
const digitMaskedKey = Pair.fnToKey((digit, m) => m === 0 || m === digit, shape);
// shade-masked: masked is 0 exactly when the cell is unshaded (so shaded
// forces masked to equal the digit, via the pairing above).
const shadeMaskedKey = Pair.fnToKey((s, m) => (s === UNSHADED) === (m === 0), shape);

const maskLinks = graph.cells().flatMap(cell => [
  new Pair(digitMaskedKey, 'digit-masked', cell, masked.at(cell)),
  new Pair(shadeMaskedKey, 'shade-masked', shade.at(cell), masked.at(cell)),
]);

// One box's shape Or: pick one of the 32 placements, which pins every shade
// cell in the box (4 shaded, 5 unshaded) and the box's tetromino-type label.
function boxShapeConstraint(b) {
  const cells = graph.box(b);
  const typeCell = typeVar.at(cells[0]);
  return new Or(PLACEMENTS.map(({ type, cells: local }) => {
    const shadedIdx = new Set(local.map(([r, c]) => r * 3 + c));
    return new And([
      new Given(typeCell, TYPE_VAL[type]),
      ...cells.map((cell, idx) =>
        new Given(shade.at(cell), shadedIdx.has(idx) ? SHADED : UNSHADED)),
    ]);
  }));
}

// One box's combo Or: the box's masked cells (0 for unshaded, the digit for
// shaded) contain exactly five 0s plus one candidate combo's four digits, and
// the combo label records which of the 12 combos that was, for AllDifferent
// across boxes below.
function boxComboConstraint(b) {
  const cells = graph.box(b);
  const maskedCells = masked.at(cells);
  const comboCell = comboVar.at(cells[0]);
  return new Or(COMBOS.map((combo, i) => new And([
    new Given(comboCell, i + 1),
    new ContainExact([0, 0, 0, 0, 0, ...combo].join('_'), ...maskedCells),
  ])));
}

// No 2x2 block of shaded cells, anywhere in the grid (box-crossing windows
// included -- the per-box shape choice only rules out a 2x2 within one box).
function no2x2Constraints() {
  const out = [];
  for (const r of rangeI(1, 8)) {
    for (const c of rangeI(1, 8)) {
      const block = graph.block(makeCellId(r, c), 2, 2);
      out.push(new Or(block.map(cell => new Given(shade.at(cell), UNSHADED))));
    }
  }
  return out;
}

const rowBands = [[1, 2, 3], [4, 5, 6], [7, 8, 9]];
const colBands = [[1, 4, 7], [2, 5, 8], [3, 6, 9]];
const bandTypeRules = [...rowBands, ...colBands].map(band =>
  new AllDifferent(...band.map(b => typeVar.at(graph.box(b)[0]))));

return [
  shape,
  graph.makeReplicate(new Given(graph.cells()[0], ...rangeI(1, 9))),
  ...givens.map(([cell, v]) => new Given(cell, v)),

  shade.toVar('shade'),
  masked.toVar('masked value'),
  typeVar.toVar('box tetromino type'),
  comboVar.toVar('box combo label'),

  ...preShaded.map(cell => new Given(shade.at(cell), SHADED)),
  new ConnectedValues('VS', SHADED),
  ...no2x2Constraints(),

  ...maskLinks,
  ...[...rangeI(1, 9)].map(b => new Sum(20, ...masked.at(graph.box(b)))),

  ...[...rangeI(1, 9)].map(boxShapeConstraint),
  ...bandTypeRules,

  ...[...rangeI(1, 9)].map(boxComboConstraint),
  new AllDifferent(...[...rangeI(1, 9)].map(b => comboVar.at(graph.box(b)[0]))),
];
